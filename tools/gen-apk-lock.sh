#!/bin/sh
# Usage: tools/gen-apk-lock.sh <alpine-version> <cri> <lock-file> [<pkg>...]
#        tools/gen-apk-lock.sh <alpine-version> <cri> <lock-file> <apks.list
#
# Installs the requested packages on alpine:<version>, then snapshots the full
# resolved set (including transitive deps) into <lock-file> with one
# `pkg=version-release` line per installed package.
#
# With no <pkg> arguments the list is read from stdin, one package per line,
# '#' starting a comment -- so the commented, human-readable apks.list can be
# the input rather than a shell variable nobody can read.
#
# The resolution happens in a throwaway alpine:<version> container, never in
# the image this repo builds: a lock generated inside the already-built image
# is a fixpoint that only ever picks up upgrades if someone remembers to run
# `apk upgrade` by hand first.
set -eu

ALPINE_VERSION=$1; shift
CRI=$1; shift
LOCK=$1; shift

if [ "$#" -gt 0 ]; then
    PACKAGES="$*"
else
    PACKAGES=$(sed -e 's/#.*//' -e '/^[[:space:]]*$/d' | tr -s '[:space:]' ' ')
fi

# Collapse whatever spacing the input had into a single line, so the header
# written into the lock reads the same however the packages arrived.
PACKAGES=$(printf '%s' "$PACKAGES" | tr -s '[:space:]' ' ' | sed 's/^ //;s/ $//')
[ -n "$PACKAGES" ] || { echo "no packages given" >&2; exit 1; }

# PACKAGES is interpolated into the shell command below, so refuse anything
# that is not a package name -- a stray ';' in the list would otherwise run in
# the container.
for pkg in $PACKAGES; do
    case $pkg in
        *[!A-Za-z0-9._+-]*) echo "not a package name: $pkg" >&2; exit 1 ;;
    esac
done

mkdir -p "$(dirname "$LOCK")"

tmp=$(mktemp)
trap 'rm -f "$tmp"' EXIT

# The snapshot itself lives in apk-installed.sh, which `mise run
# image:packages` also uses to read back a built image -- the two have to
# produce the same line format for the diff between them to mean anything.
# What is specific to generating a lock is the setup below.
#
# The alpine:<version> image ships a base set frozen at image-build time (e.g.
# apk-tools 3.0.6-r0 while v3.24/main already carries 3.0.8-r0), and apk add
# leaves already-satisfied packages alone. Without this upgrade the lock pins
# those stale versions and never picks up branch updates. Not
# 'apk add --upgrade': that only covers the named packages and their dependency
# closure, leaving busybox / ssl_client behind.
"$(dirname "$0")/apk-installed.sh" "$CRI" "alpine:$ALPINE_VERSION" "
    apk upgrade --no-cache
    apk add --no-cache $PACKAGES
" >"$tmp"

{
    echo "# Generated by tools/gen-apk-lock.sh on alpine:$ALPINE_VERSION"
    echo "# Regenerate via: mise run image:apk-lock"
    echo "# Direct packages: $PACKAGES"
    sort -u "$tmp"
} >"$LOCK"

echo "wrote $LOCK ($(grep -c '^[^#]' "$LOCK") packages)" >&2
